#!/usr/bin/env node
/** Sync a tagged music-assistant/shared-icons release into the frontend. */
import { cp, mkdtemp, mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { tmpdir } from "node:os";
import prettier from "prettier";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const vendorDir = join(ROOT, "src", "vendor", "shared-icons");
const sourceLockPath = join(vendorDir, "source.json");
const generatedPath = join(
  ROOT,
  "src",
  "components",
  "ma-icons",
  "generated.ts",
);
const idPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
// The renderer puts SVG markup into innerHTML, so nothing executable may get in.
const unsafeSvg = /<script|<foreignObject|<style|href=|url\(|\son[a-z]+\s*=/i;
const execFileAsync = promisify(execFile);

const readJson = async (path) => JSON.parse(await readFile(path, "utf8"));
// Resolve the repo config so vendored files follow it, JSON is 4 spaces here.
const format = async (path, text) =>
  prettier.format(text, {
    ...(await prettier.resolveConfig(path, { editorconfig: true })),
    filepath: path,
  });
const { tag, sourceDir, commit, local, cleanup } = await getSource();

try {
  const manifest = await readJson(join(sourceDir, "manifest.json"));

  // Upstream CI validates the full contract. Only what codegen and the
  // renderer depend on is checked again here, so a bad release stops early.
  if (!Array.isArray(manifest.icons) || manifest.icons.length === 0) {
    throw new Error("Shared-icons manifest must contain at least one icon");
  }
  for (const id of manifest.icons) {
    // Ids become import paths and identifiers in generated.ts.
    if (typeof id !== "string" || !idPattern.test(id)) {
      throw new Error(`Shared-icons manifest has an invalid icon id: ${id}`);
    }
    const svg = await readFile(join(sourceDir, "icons", `${id}.svg`), "utf8");
    if (unsafeSvg.test(svg)) {
      throw new Error(
        `Shared-icons icons/${id}.svg contains executable content`,
      );
    }
  }

  await rm(join(vendorDir, "icons"), { force: true, recursive: true });
  await mkdir(vendorDir, { recursive: true });
  await cp(join(sourceDir, "icons"), join(vendorDir, "icons"), {
    recursive: true,
  });
  await Promise.all(
    ["manifest.json", "meta.json"].map(async (file) => {
      const target = join(vendorDir, file);
      const formatted = await format(
        target,
        await readFile(join(sourceDir, file), "utf8"),
      );
      await writeFile(target, formatted);
    }),
  );
  if (!local) {
    await writeFile(
      sourceLockPath,
      await format(
        sourceLockPath,
        `${JSON.stringify(
          { repository: "music-assistant/shared-icons", tag, commit },
          null,
          2,
        )}\n`,
      ),
    );
  }

  const svgImports = manifest.icons
    .map(
      (id) =>
        `import ${toIdentifier(id)} from "@/vendor/shared-icons/icons/${id}.svg?raw";`,
    )
    .join("\n");
  const registry = manifest.icons
    .map((id) => `  "${id}": makeSvgIcon("${id}", ${toIdentifier(id)}),`)
    .join("\n");

  await writeFile(
    generatedPath,
    await format(
      generatedPath,
      `// Generated by scripts/sync-shared-icons.mjs from shared-icons ${tag} (${commit}). Do not edit.\nimport { makeSvgIcon } from "./_make-icon";\nimport type { Component } from "vue";\n\n${svgImports}\n\nexport const registry: Record<string, Component> = {\n${registry}\n};\n\nexport const Speakers = registry["speakers"];\n`,
    ),
  );

  console.log(
    local
      ? `Synced shared-icons from ${sourceDir}: ${manifest.icons.length} icons (source.json left unchanged)`
      : `Synced shared-icons ${tag} (${commit.slice(0, 7)}): ${manifest.icons.length} icons`,
  );
} finally {
  await cleanup();
}

async function getSource() {
  const args = process.argv.slice(2);
  const usage = "Usage: pnpm sync:shared-icons [tag] [--source <directory>]";
  let sourcePath;
  let tag;

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (arg === "--source") {
      sourcePath = args[index + 1];
      if (!sourcePath) throw new Error("--source requires a directory path");
      index += 1;
    } else if (arg.startsWith("-") || tag) {
      throw new Error(usage);
    } else {
      tag = arg;
    }
  }

  if (sourcePath) {
    // A local source has no tag to pin, so source.json is left alone.
    if (tag) throw new Error("--source cannot be combined with a tag");
    return {
      tag: "local",
      sourceDir: resolve(sourcePath),
      commit: "local",
      local: true,
      cleanup: async () => {},
    };
  }

  const lock = tag ? undefined : await readJson(sourceLockPath);
  const resolvedTag = tag ?? lock?.tag;
  if (typeof resolvedTag !== "string" || !resolvedTag) {
    throw new Error("A shared-icons tag is required");
  }

  const temporaryDir = await mkdtemp(join(tmpdir(), "shared-icons-"));
  try {
    await execFileAsync("git", [
      "clone",
      "--depth",
      "1",
      "--branch",
      resolvedTag,
      "https://github.com/music-assistant/shared-icons.git",
      temporaryDir,
    ]);
    const { stdout } = await execFileAsync("git", [
      "-C",
      temporaryDir,
      "rev-parse",
      "HEAD",
    ]);
    const commit = stdout.trim();
    if (lock && lock.commit !== commit) {
      throw new Error(
        `Recorded shared-icons commit ${lock.commit} does not match ${resolvedTag} (${commit})`,
      );
    }
    return {
      tag: resolvedTag,
      sourceDir: temporaryDir,
      commit,
      cleanup: () => rm(temporaryDir, { force: true, recursive: true }),
    };
  } catch (error) {
    await rm(temporaryDir, { force: true, recursive: true });
    throw error;
  }
}

function toIdentifier(id) {
  return `icon_${id.replaceAll("-", "_")}`;
}
